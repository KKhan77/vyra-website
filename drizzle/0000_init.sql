CREATE TABLE "project_briefs" (
	"id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
	"reference" varchar(24) NOT NULL,
	"kind" varchar(24) DEFAULT 'project' NOT NULL,
	"name" varchar(160) NOT NULL,
	"company" varchar(200) DEFAULT '' NOT NULL,
	"email" varchar(254) NOT NULL,
	"phone" varchar(60),
	"website" varchar(500),
	"industry" varchar(100),
	"project_type" varchar(100) NOT NULL,
	"objective" text,
	"deliverables" text[] DEFAULT '{}' NOT NULL,
	"markets" varchar(500),
	"languages" text[] DEFAULT '{}' NOT NULL,
	"budget" varchar(100),
	"timeline" varchar(100),
	"message" text,
	"attachment_name" varchar(255),
	"attachment_type" varchar(100),
	"attachment_data" text,
	"consent" boolean NOT NULL,
	"status" varchar(24) DEFAULT 'new' NOT NULL,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "project_briefs_reference_unique" UNIQUE("reference")
);
